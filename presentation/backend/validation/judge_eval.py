"""
Measure the Investigator overclaim judge on labelled live answers (operator-approved live calls).

    python presentation/backend/validation/judge_eval.py --split design   # dev + holdout answers
    python presentation/backend/validation/judge_eval.py --split test     # round-2 answers, scored once

Answers are pseudonymized (IPs, person IDs) before they are sent, as in the
Investigator. Ground truth: claim_check_labels.json. An answer is positive when
labelled with a presence, causation or absence overclaim. The judge's
instructions were designed on the "design" split only.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

DATA = ROOT / "presentation" / "backend" / "data" / "claim_check_eval"
LABELS = Path(__file__).resolve().parent / "claim_check_labels.json"
RESULTS = Path(__file__).resolve().parent / "results"
TYPES = {"PHYSICAL_PRESENCE": "PRESENCE", "CAUSATION": "CAUSATION"}


def design_items(labels):
    items = []
    for split in ("dev", "holdout"):
        answers = json.loads((DATA / f"answers_{split}.json").read_text(encoding="utf-8"))
        for a in answers:
            label = labels[split][a["case_id"]]
            items.append({"id": f"{split}:{a['case_id']}", "answer": a["answer"] or "",
                          "truth": sorted({TYPES.get(b, b) for b in label["boundary"]})})
    return items


def test_items(labels):
    blind = {b["id"]: b for b in json.loads((DATA / "round2_blind.json").read_text(encoding="utf-8"))}
    truth = json.loads((DATA / "round2_blind_labels.json").read_text(encoding="utf-8"))["overclaims"]
    names = {"presence": "PRESENCE", "causation": "CAUSATION", "absence": "ABSENCE"}
    return [{"id": bid, "answer": b["answer"] or "", "truth": [names[truth[bid]]] if bid in truth else []}
            for bid, b in sorted(blind.items())]


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--split", choices=["design", "test"], required=True)
    args = parser.parse_args()
    from presentation.backend.app.investigator_judge import judge
    from presentation.backend.app.investigator_pseudonyms import Pseudonymizer
    labels = json.loads(LABELS.read_text(encoding="utf-8"))
    items = design_items(labels) if args.split == "design" else test_items(labels)
    rows = []
    for item in items:
        result = judge(Pseudonymizer().text(item["answer"]))
        flagged = sorted({f["type"] for f in result["findings"]})
        rows.append({**item, "status": result["status"], "flagged": flagged,
                     "findings": [{"type": f["type"], "sentence": f["sentence"][:160]} for f in result["findings"]]})
        print(item["id"], "truth", item["truth"], "judge", result["status"], flagged, flush=True)
    positive = [r for r in rows if r["truth"]]
    negative = [r for r in rows if not r["truth"]]
    tp = sum(bool(r["flagged"]) for r in positive)
    fp = sum(bool(r["flagged"]) for r in negative)
    summary = {"split": args.split, "answers": len(rows), "positives": len(positive), "tp": tp, "fn": len(positive) - tp,
               "fp": fp, "tn": len(negative) - fp,
               "recall": round(tp / len(positive), 3) if positive else None,
               "precision": round(tp / (tp + fp), 3) if tp + fp else None,
               "false_alarm_rate": round(fp / len(negative), 3) if negative else None,
               "type_match_on_tp": sum(bool(set(r["truth"]) & set(r["flagged"])) for r in positive if r["flagged"]),
               "unavailable": sum(r["status"] == "UNAVAILABLE" for r in rows)}
    (DATA / f"judge_{args.split}.json").write_text(json.dumps(rows, indent=1, ensure_ascii=False), encoding="utf-8")
    RESULTS.mkdir(parents=True, exist_ok=True)
    lines = [f"# Investigator overclaim judge — {args.split} split", "",
             "Generated by `presentation/backend/validation/judge_eval.py` (answers pseudonymized; author labels). "
             "Per-answer findings are local because they quote Evidence.", "", "| Measure | Value |", "|---|---:|"]
    lines += [f"| {k.replace('_', ' ')} | {v} |" for k, v in summary.items()]
    (RESULTS / f"judge_{args.split}.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps(summary, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
