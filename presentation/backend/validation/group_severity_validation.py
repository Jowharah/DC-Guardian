"""
Validation of the provisional group severity (DCG-UNIFIED-SEVERITY-PROVISIONAL-v1)
against the labelled uncertainty scenarios.

The scenarios carry incident labels but no severity labels, so this cannot show
that a level is "right". It tests whether group severity is a trustworthy
priority signal: when the system forms a group of correlated abnormal events
and assigns it a severity, how often is that group one genuine incident rather
than a coincidence? Groups are formed per scenario exactly as the live system
does (connected components of 3+ correlated events; pairs are reported too),
using the crisp rule and, for comparison, the Bayesian model.

    python presentation/backend/validation/group_severity_validation.py

Writes presentation/backend/validation/results/group_severity_validation.md.
The test split is the primary result.
"""

from __future__ import annotations

import sys
from collections import defaultdict
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[3]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from presentation.backend.app.unified_severity import group_severity  # noqa: E402
from reasoning.uncertainty.bayesian_correlation import is_abnormal, load_knowledge_base  # noqa: E402
from reasoning.uncertainty.evaluate import components, load_scenarios, score_rows  # noqa: E402

RESULTS = Path(__file__).resolve().parent / "results" / "group_severity_validation.md"
LEVELS = ("HIGH", "MEDIUM", "LOW")


def groups_for(scenario, rows, key):
    events = {e["event_id"]: e for e in scenario["events"] if is_abnormal(e)}
    links = [tuple(r["event_ids"]) for r in rows if r["scenario_id"] == scenario["scenario_id"] and r[key]]
    result = []
    for members in components(list(events), links):
        if len(members) < 2:
            continue
        incidents = {events[m]["ground_truth_incident"] for m in members}
        genuine = len(incidents) == 1 and None not in incidents
        member_view = [{"kind": events[m]["domain"].lower(), "domain": events[m]["domain"],
                        "effective_state": events[m].get("authorization") or events[m]["state"],
                        "active_concern": True} for m in members]
        result.append({"size": len(members), "genuine": genuine,
                       "severity": group_severity(member_view)["severity"],
                       "domains": len({events[m]["domain"] for m in members})})
    return result


def table(groups):
    by_level = defaultdict(list)
    for g in groups:
        by_level[g["severity"]].append(g)
    lines = ["| Severity | Groups | Genuine incident | Share genuine |", "|---|---:|---:|---:|"]
    for level in LEVELS:
        items = by_level.get(level, [])
        share = f"{100 * sum(g['genuine'] for g in items) / len(items):.0f}%" if items else "–"
        lines.append(f"| {level} | {len(items)} | {sum(g['genuine'] for g in items)} | {share} |")
    return lines


def main() -> int:
    knowledge_base = load_knowledge_base()
    scenarios = load_scenarios()
    rows = score_rows(scenarios, knowledge_base)
    lines = ["# Provisional group severity — validation on labelled scenarios", "",
             "Generated by `presentation/backend/validation/group_severity_validation.py`. A group is **genuine** when all "
             "its events belong to one labelled incident. The scenarios have no severity labels, so this measures whether "
             "severity is a trustworthy priority signal, not whether each level is correct.", ""]
    summary = {}
    for split in ("test", "all"):
        subset = [s for s in scenarios if split == "all" or s["split"] == split]
        for key, method in (("crisp", "Crisp rule (live system)"), ("bayesian", "Bayesian model (research)")):
            groups = [g for s in subset for g in groups_for(s, rows, key)]
            for label, selection in (("All groups (2+ events)", groups), ("Unified groups (3+ events)", [g for g in groups if g["size"] >= 3])):
                lines += [f"## {split.capitalize()} split · {method} · {label}", "", *table(selection), ""]
            summary[(split, key)] = groups
    test_crisp = summary[("test", "crisp")]
    high = [g for g in test_crisp if g["severity"] == "HIGH"]
    lines += ["## Reading", "",
              f"On the test split the live rule forms {len(test_crisp)} groups; {len(high)} are HIGH, of which "
              f"{sum(g['genuine'] for g in high)} are one genuine incident. Severity here depends only on which "
              "domains are present (three or more domains give HIGH), so a coincidental group spanning many domains is "
              "rated as severe as a real multi-domain incident. Treat group severity as provisional until severity labels "
              "exist; a severity column could be added to the independent labelling pack.", ""]
    RESULTS.parent.mkdir(parents=True, exist_ok=True)
    RESULTS.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines[-3:-1]))
    print(f"Report: {RESULTS.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
