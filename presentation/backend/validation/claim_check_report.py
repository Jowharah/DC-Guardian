"""
Score the Investigator claim checker against human labels of live answers.

    python presentation/backend/validation/claim_check_report.py --set dev
    python presentation/backend/validation/claim_check_report.py --set holdout

Answers come from claim_check_collect.py (local, not committed: they contain
Evidence). Labels (claim_check_labels.json, committed: case IDs and judgements
only) say, per answer, which problems a careful reader finds:
  boundary  - overclaims of the kinds the checker covers (CAUSATION, IDENTITY,
              PHYSICAL_PRESENCE, COMPROMISE, AUTONOMOUS_ACTION)
  state     - a detector or human state stated wrongly
  other     - errors outside the checker's scope (free text)

The current checker is re-run on each stored answer, against the record the
Investigator saw (re-read from the local context endpoint, no OpenAI call).
Answer level: a positive is an answer with an in-scope problem; the checker
"flags" an answer when its status is VIOLATION or MISMATCH. HEDGED is reported
separately and not counted as a flag.

Protocol: the checker was changed using the dev set only; the holdout set was
collected after those changes and is scored once. Labels are the author's.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

DATA = ROOT / "presentation" / "backend" / "data" / "claim_check_eval"
LABELS = Path(__file__).resolve().parent / "claim_check_labels.json"
RESULTS = Path(__file__).resolve().parent / "results"


def record_for(kind, evidence_id, cache):
    """The record the Investigator saw: saved assessment plus the human-verdict summary."""
    key = (kind, evidence_id)
    if key not in cache:
        from presentation.backend.app.authorization import Principal
        from presentation.backend.app.investigator_tools import single_evidence_context
        admin = Principal("claim-check-eval", frozenset({"administrator"}), frozenset({"ZONE-A", "ZONE-B", "ZONE-C"}))
        context = single_evidence_context(kind, evidence_id, admin)
        cache[key] = {**context["source_assessment"], "human_review": context.get("human_review")}
    return cache[key]


def score(answers, labels):
    from presentation.backend.app.investigator_claim_checks import claim_checks
    cache, rows = {}, []
    for answer in answers:
        label = labels[answer["case_id"]]
        result = claim_checks(answer["answer"] or "", [(answer["kind"], answer["evidence_id"],
                                                         record_for(answer["kind"], answer["evidence_id"], cache))])
        problem = bool(label["boundary"]) or label["state"]
        flagged = result["status"] in ("VIOLATION", "MISMATCH")
        rows.append({"case_id": answer["case_id"], "kind": answer["kind"], "question": answer["question"],
                     "label_problem": problem, "label": label, "checker": result["status"], "flagged": flagged,
                     "hedged": result["status"] == "HEDGED"})
    tp = sum(r["label_problem"] and r["flagged"] for r in rows)
    fp = sum(not r["label_problem"] and r["flagged"] for r in rows)
    fn = sum(r["label_problem"] and not r["flagged"] for r in rows)
    tn = sum(not r["label_problem"] and not r["flagged"] for r in rows)
    return rows, {"answers": len(rows), "with_in_scope_problem": tp + fn, "tp": tp, "fp": fp, "fn": fn, "tn": tn,
                  "recall": round(tp / (tp + fn), 3) if tp + fn else None,
                  "precision": round(tp / (tp + fp), 3) if tp + fp else None,
                  "false_alarm_rate": round(fp / (fp + tn), 3) if fp + tn else None,
                  "hedged_answers": sum(r["hedged"] for r in rows),
                  "out_of_scope_errors": sum(bool(r["label"]["other"]) for r in rows)}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--set", choices=["dev", "holdout"], required=True)
    args = parser.parse_args()
    answers = json.loads((DATA / f"answers_{args.set}.json").read_text(encoding="utf-8"))
    labels = json.loads(LABELS.read_text(encoding="utf-8"))[args.set]
    rows, summary = score(answers, labels)
    RESULTS.mkdir(parents=True, exist_ok=True)
    lines = [f"# Claim checker evaluation — {args.set} set", "",
             "Generated by `presentation/backend/validation/claim_check_report.py`. Live Investigator answers "
             "(gpt-4.1-mini, operator-approved), labelled by the author; current checker re-run on each answer. "
             "Answer texts are local (they contain Evidence) and are not reproduced here.", "",
             "| Measure | Value |", "|---|---:|"]
    lines += [f"| {k.replace('_', ' ')} | {v} |" for k, v in summary.items()]
    lines += ["", "| Case | Domain | Question | Labelled problem | Checker |", "|---|---|---|---|---|"]
    for r in rows:
        found = ", ".join(r["label"]["boundary"] + (["state"] if r["label"]["state"] else [])) or "none"
        if r["label"]["other"]:
            found += f" (out of scope: {r['label']['other']})"
        lines.append(f"| {r['case_id']} | {r['kind']} | {r['question']} | {found} | {r['checker']} |")
    out = RESULTS / f"claim_check_{args.set}.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps(summary, indent=2))
    print(f"Report: {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
