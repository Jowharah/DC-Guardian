"""
Upload latency with one worker process per upload versus persistent workers.

Uses the latency benchmark's upload stage (same inputs, same endpoints,
publish/retain off, temporary database, no OpenAI call), run twice:
DCG_PERSISTENT_WORKERS=0 (the original behaviour) and =1. With persistent
workers the first upload still starts the worker and loads the model, so the
first call is reported separately from the warm median.

    python presentation/backend/validation/persistent_workers_benchmark.py [--repeats N]

Writes results/persistent_workers_benchmark.{md,json}.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import tempfile
import time
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import latency_benchmark as lb  # noqa: E402

RESULTS = HERE / "results"


def comparable(response: dict) -> dict:
    """The response without fields that legitimately differ between runs."""
    response = json.loads(json.dumps(response))
    response.pop("preview_id", None)
    if isinstance(response.get("assessment"), dict):
        response["assessment"].pop("latency_ms", None)
    return response


def stage(persistent: bool, repeats: int, responses: dict) -> dict:
    os.environ["DCG_PERSISTENT_WORKERS"] = "1" if persistent else "0"
    from presentation.backend.app import inference_workers
    inference_workers.shutdown_all()  # start cold
    from fastapi.testclient import TestClient
    from presentation.backend.app.authentication import current_principal
    from presentation.backend.app.authorization import Principal
    from presentation.backend.app.custom_scenarios import topology_options
    from presentation.backend.app.main import app

    zone = next(z for z in topology_options() if z["zone_id"] == "ZONE-A")
    app.dependency_overrides[current_principal] = lambda: Principal(
        "latency-benchmark", frozenset({"administrator"}), frozenset({"ZONE-A", "ZONE-B", "ZONE-C"}))
    client = TestClient(app)
    calls = {
        "SSH log (OpenSSH_2k)": lambda: client.post(
            "/api/v1/ssh/validate-log", files={"log": ("input.log", lb.SSH_LOG.read_bytes(), "text/plain")},
            data={"zone_id": "ZONE-A", "server_id": zone["servers"][0]}),
        "PPE image": lambda: client.post(
            "/api/v1/ppe/validate-image", files={"image": ("input.jpg", lb.PPE_IMAGE.read_bytes(), "image/jpeg")}),
        "Face image": lambda: client.post(
            "/api/v1/face/validate-image", files={"image": ("input.jpg", lb.FACE_IMAGE.read_bytes(), "image/jpeg")}),
    }
    out = {}
    try:
        for name, call in calls.items():
            start = time.perf_counter()
            response = call()
            status = response.status_code
            first = (time.perf_counter() - start) * 1000
            if status == 200:
                responses.setdefault(name, []).append(comparable(response.json()))
            if status != 200:
                out[name] = {"skipped": f"endpoint answered {status}"}
                continue
            out[name] = {"first_call_ms": round(first, 1), **lb.summary(lb.timed(call, repeats))}
            print(f"  persistent={persistent} {name}: {out[name]}")
    finally:
        app.dependency_overrides.pop(current_principal, None)
        inference_workers.shutdown_all()
    return out


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--repeats", type=int, default=10)
    args = parser.parse_args()
    os.environ["DCG_INVESTIGATOR_ENABLED"] = "0"
    with tempfile.TemporaryDirectory(prefix="dcg-workers-") as folder:
        os.environ["DCG_PRESENTATION_DB"] = str(Path(folder) / "presentation.sqlite3")
        responses: dict[str, list] = {}
        before = stage(False, args.repeats, responses)
        after = stage(True, args.repeats, responses)
    identical = {name: len(r) == 2 and r[0] == r[1] for name, r in responses.items()}
    report = {"run_at": datetime.now(timezone.utc).isoformat(timespec="seconds"), "repeats": args.repeats,
              "ppe_detector": os.environ.get("DCG_PPE_DETECTOR", "v2m (default)"),
              "one_process_per_upload": before, "persistent_workers": after,
              "identical_results_except_latency_ms": identical}
    lines = ["# Upload latency: one process per upload vs persistent workers", "",
             f"Generated by `presentation/backend/validation/persistent_workers_benchmark.py` on {report['run_at']} "
             f"({args.repeats} timed uploads per row after the first). Upload endpoints with publish/retain off, "
             "temporary database, no OpenAI call; PPE detector as configured "
             f"({report['ppe_detector']}).", "",
             "| Upload | Per upload, median (before) | Persistent: first upload (starts worker) | Persistent: median | Persistent: p95 | Same result |",
             "|---|---:|---:|---:|---:|---|"]
    for name in before:
        b, a = before[name], after.get(name, {})
        if "skipped" in b or "skipped" in a:
            lines.append(f"| {name} | {b.get('skipped', b.get('median_ms'))} | – | {a.get('skipped', '–')} | – |")
            continue
        lines.append(f"| {name} | {b['median_ms'] / 1000:.2f} s | {a['first_call_ms'] / 1000:.2f} s | "
                     f"**{a['median_ms'] / 1000:.2f} s** | {a['p95_ms'] / 1000:.2f} s | "
                     f"{'yes' if identical.get(name) else 'NO'} |")
    lines += ["", "Same result: the first upload's response in both modes is identical apart from the worker's own "
                  "`latency_ms` field (and the SSH preview ID).", "",
              "Persistent workers stop after 15 minutes without use (DCG_WORKER_IDLE_SECONDS), so the next upload "
                  "pays the first-upload time again. DCG_PERSISTENT_WORKERS=0 restores one process per upload.", ""]
    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / "persistent_workers_benchmark.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    (RESULTS / "persistent_workers_benchmark.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
